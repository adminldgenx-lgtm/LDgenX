// The lists the content API checks against, generated from the built site: its pictures, its
// addresses and the pages that can be edited. Publishes nothing.
import { readdir, writeFile } from "node:fs/promises";
const source = await import("../.prerender/entry-server.js");
await source.ready;
const files = await readdir("public/images");
const paths = source.pages.map((p) => p.path);
await writeFile(
  "supabase/functions/_shared/editorial-static.ts",
  `// Generated by scripts/prepare-editorial.mjs from the checked public assets and routes.\nexport const editorialStaticImages: string[] = ${JSON.stringify(files.filter((f) => /\.(webp|png|jpg)$/.test(f)).map((f) => "/images/" + f))};\nexport const editorialStaticPaths: string[] = ${JSON.stringify(paths)};\n`,
);
// Existing page templates are editable through a route allowlist, without replacing their layout.
const editableKinds = new Set([
  "home",
  "services",
  "service",
  "applications",
  "application",
  "studies",
  "publications",
  "resources",
  "innovations",
  "innovation",
  "about",
  "team",
  "partners",
  "person",
  "faq",
  "glossary",
  "contact",
]);
const plain = (value) =>
  String(value)
    .replace(/<br\s*\/?\s*>/gi, "\n")
    .replace(/<[^>]*>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\s+/g, " ")
    .trim();
const pageTemplates = source.pages
  .filter((p) => editableKinds.has(p.kind))
  .map((p) => {
    const html = source.render(p.path).html;
    return {
      path: p.path,
      locale: p.locale,
      label: p.label,
      kind: p.kind,
      alternates: p.alternates,
      title: plain(html.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i)?.[1] || p.label),
      summary: plain(
        html.match(
          /<p class="(?:lead|dna-hero-intro)"[^>]*>([\s\S]*?)<\/p>/i,
        )?.[1] || p.description,
      ),
    };
  });
await writeFile(
  "supabase/functions/_shared/editorial-pages.ts",
  "// Generated from existing public page templates. No private data.\nexport const editorialPageTemplates = " +
    JSON.stringify(pageTemplates) +
    ";\n",
);
console.log(
  "Prepared " + pageTemplates.length + " editable website page templates.",
);
