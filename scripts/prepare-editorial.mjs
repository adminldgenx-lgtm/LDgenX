// Lossless text import from the validated bilingual catalogues. Never publishes or overwrites edits.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const source = await import("../.prerender/entry-server.js");
await source.ready;
const files = await readdir("public/images");
const paths = source.pages.map((p) => p.path);
await writeFile(
  "supabase/functions/_shared/editorial-static.ts",
  `// Generated by scripts/prepare-editorial.mjs from the checked public assets and routes.\nexport const editorialStaticImages: string[] = ${JSON.stringify(files.filter((f) => /\.(webp|png|jpg)$/.test(f)).map((f) => "/images/" + f))};\nexport const editorialStaticPaths: string[] = ${JSON.stringify(paths)};\n`,
);
const photoRegistry = JSON.parse(
  await readFile("data/licensed-photos.json", "utf8"),
).photos;
function uuid(key) {
  const h = createHash("sha256")
    .update("ldgenx-editorial:" + key)
    .digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
function image(name, alt = "", caption = "", credit = "", licenceUrl = "") {
  const variants = files
    .filter((f) => f.startsWith(name + "-") && /-\d+\.webp$/.test(f))
    .sort(
      (a, b) =>
        Number(a.match(/-(\d+)\.webp$/)[1]) -
        Number(b.match(/-(\d+)\.webp$/)[1]),
    );
  if (!variants.length) throw new Error(`Missing source image: ${name}`);
  const known = photoRegistry.find((p) => p.name === name);
  return {
    staticSrc: "/images/" + variants.at(-1),
    alt: alt || caption || name.replaceAll("-", " "),
    caption,
    credit: credit || (known ? `${known.author} · ${known.licence}` : "LDgenX"),
    licenceUrl: licenceUrl || known?.source || "",
  };
}
function rich(text) {
  const out = [];
  const pattern = /\[([^\]]+)\]\(([^)]+)\)|\*([^*]+)\*/g;
  let end = 0;
  for (const m of String(text).matchAll(pattern)) {
    if (m.index > end)
      out.push({ type: "text", text: text.slice(end, m.index) });
    out.push({
      type: "text",
      text: m[1] || m[3],
      marks: [
        m[1] ? { type: "link", attrs: { href: m[2] } } : { type: "italic" },
      ],
    });
    end = m.index + m[0].length;
  }
  if (end < text.length) out.push({ type: "text", text: text.slice(end) });
  return out;
}
const paragraph = (text) => ({ type: "paragraph", content: rich(text) });
const heading = (text) => ({
  type: "heading",
  attrs: { level: 2 },
  content: rich(text),
});
const section = (title, text) => [
  heading(title),
  ...text.split(/\n\n+/).map(paragraph),
];
const entries = [];
for (const [locale, c] of Object.entries(source.catalogs)) {
  const fr = locale === "fr";
  const make = (kind, item, document) => {
    const page = source.pages.find(
      (p) => p.locale === locale && p.kind === kind && p.id === item.id,
    );
    if (!page) throw new Error(`Missing route ${kind}/${item.id}`);
    entries.push({
      id: uuid(`${kind}:${locale}:${item.id}`),
      kind,
      locale,
      slug: page.path.split("/").at(-1),
      groupId: uuid(`${kind}:${item.id}`),
      legacyId: item.id,
      document: {
        title: item.title,
        summary: "",
        category: "",
        author: "LDgenX",
        seoTitle: item.seoTitle || "",
        seoDescription: "",
        cover: null,
        body: { type: "doc", content: [] },
        references: [],
        doi: "",
        journal: "",
        year: "",
        reviewed: false,
        ...document,
      },
    });
  };
  for (const r of c.resources)
    make("article", r, {
      summary: r.intro,
      category: r.category,
      cover: image(r.image),
      body: {
        type: "doc",
        content: r.sections.flatMap((s) => section(s.title, s.text)),
      },
      references: r.source
        ? [{ label: fr ? "Source LDgenX" : "LDgenX source", url: r.source }]
        : [],
    });
  for (const s of c.studies) {
    const body = [
      ...s.facts.map((f) => paragraph(`${f.label} : ${f.value}`)),
      ...section(fr ? "Contexte" : "Context", s.context),
      ...section(fr ? "Question" : "Question", s.question),
      ...section(fr ? "Approche" : "Approach", s.approach),
      ...section(fr ? "Résultats et portée" : "Results and scope", s.result),
    ];
    if (s.id === c.featuredStudy.slug || s.details)
      body.push({ type: "studyEvidence", attrs: { id: s.id } });
    make("study", s, {
      summary: s.subtitle,
      category: s.category,
      cover: image(s.image, s.imageAlt),
      body: { type: "doc", content: body },
      references: s.source
        ? [{ label: fr ? "Source de l’étude" : "Study source", url: s.source }]
        : [],
    });
  }
  for (const p of c.research.publications) {
    const body = [
      paragraph(`${p.journal} · ${p.year} · ${p.issue}`),
      ...(p.authorNote ? [paragraph(p.authorNote)] : []),
      paragraph(
        `${fr ? "Texte consulté" : "Source consulted"} : ${p.text === "abstract" ? (fr ? "résumé publié" : "published abstract") : p.text === "preprint" ? (fr ? "prépublication" : "preprint") : fr ? "article publié" : "published article"}. ${fr ? "Licence" : "Licence"} : ${p.licence}.`,
      ),
      ...section(fr ? "La question" : "The question", p.question),
      ...section(fr ? "L’approche" : "The approach", p.approach),
      ...section(
        fr ? "Ce que l’article apporte" : "What the paper adds",
        p.finding,
      ),
      ...section(fr ? "Les limites" : "Limitations", p.limit),
      ...p.figures.map((f) => ({
        type: "figure",
        attrs: image(
          f.image,
          `${f.label} — ${p.title}`,
          `${f.label} — ${f.caption}`,
          `${f.credit} · ${f.licence}`,
          `https://doi.org/${p.doi}`,
        ),
      })),
    ];
    make("publication", p, {
      title: p.readingTitle,
      summary: p.summary,
      category: fr ? "Publication scientifique" : "Scientific publication",
      author: p.authors.join("; "),
      seoTitle: p.seoTitle,
      body: { type: "doc", content: body },
      doi: p.doi,
      journal: p.journal,
      year: String(p.year),
      references: [
        { label: p.title, url: `https://doi.org/${p.doi}` },
        ...p.links,
        ...(p.preprint
          ? [{ label: fr ? "Prépublication" : "Preprint", url: p.preprint }]
          : []),
      ],
    });
  }
}
await writeFile(
  ".prerender/editorial-seed.json",
  JSON.stringify(entries, null, 2) + "\n",
);
console.log(
  `Prepared ${entries.length} private working copies and static asset/route allowlists. No public content changed.`,
);
