// No image generation or upscaling: these are the raster images embedded in the client's export.
import fs from 'node:fs';
import path from 'node:path';
const { default: sharp } = await import(process.env.LDGENX_SHARP_PATH || 'sharp');
(async () => {
  const manifest = JSON.parse(fs.readFileSync('data/client-photos.json', 'utf8'));
  const publicPhotos = {};
  for (const item of manifest.photos) {
    const metadata = await sharp(item.sourceFile).metadata();
    item.width = metadata.width; item.height = metadata.height;
    if (item.usage === 'retained-not-displayed') continue;
    const widths = [...new Set([480, 860, 1100, metadata.width].filter((x) => x <= metadata.width))].sort((a,b) => a-b);
    for (const width of widths) await sharp(item.sourceFile).rotate().resize({width,withoutEnlargement:true}).webp({quality:84}).toFile(path.join('public/images',`${item.name}-${width}.webp`));
    publicPhotos[item.name] = {widths,width:metadata.width,height:metadata.height,altFr:item.altFr,altEn:item.altEn,...(item.credit ? {credit:item.credit} : {})};
  }
  fs.writeFileSync('data/client-photos.json', JSON.stringify(manifest, null, 2)+'\n');
  fs.writeFileSync('src/content/client-photos.ts', '// Generated by scripts/prepare-client-photos.mjs; source and credits in data/client-photos.json.\nexport const clientPhotos: Record<string, {widths: number[]; width: number; height: number; altFr: string; altEn: string; credit?: string}> = '+JSON.stringify(publicPhotos,null,2)+';\n');
  console.log('Prepared',Object.keys(publicPhotos).length,'photos at or below their exported resolution.');
})();
