// The client source stays internal. Only publishable associations enter the language catalogues.
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const source = JSON.parse(readFileSync(new URL('../data/assay-targets.json', import.meta.url), 'utf8'));
const targets = source.targets;
assert.equal(targets.length, 22, 'Keep all 22 entries supplied by the client');
assert.equal(new Set(targets.map((x) => x.id)).size, 22, 'Duplicate target ID');
assert.equal(new Set(targets.map((x) => x.latin)).size, 22, 'Duplicate scientific name');
for (const x of targets) {
  assert.equal(x.source, source.source.id, 'Missing client provenance');
  assert.ok(['mammals', 'fish', 'reptiles', 'invertebrates'].includes(x.category));
  assert.ok(['publish', 'hold'].includes(x.publication));
  assert.ok(!x.latin.includes('_'));
  if (x.publication === 'publish') assert.ok(x.nameFr && x.nameEn);
  else assert.ok(x.confirmation?.question && x.confirmation?.reference);
}
assert.deepEqual(targets.filter((x) => x.publication === 'hold').map((x) => x.latin), ['Neomys anomalus']);
const published = targets.filter((x) => x.publication === 'publish');
let output = '// Generated by scripts/build-assay-targets.mjs from data/assay-targets.json.\n';
output += '// Held source entries are intentionally excluded from the public bundle.\n';
output += "import type { AssayTarget } from './types';\n\n";
for (const lang of ['Fr', 'En']) {
  const rows = published.map((x) => ({
    id: x.id, name: x[`name${lang}`], latin: x.latin, category: x.category,
    searchNames: [x.nameFr, x.nameEn], source: x.source,
  }));
  output += `export const assayTargets${lang}: AssayTarget[] = ${JSON.stringify(rows, null, 2)};\n\n`;
}
const destination = new URL('../src/content/assay-targets.ts', import.meta.url);
if (process.argv.includes('--check')) assert.equal(readFileSync(destination, 'utf8'), output, 'Regenerate the assay catalogue');
else writeFileSync(destination, output);
console.log('22 source entries, 21 publishable, 1 held for taxonomy confirmation; provenance and generated catalogues checked.');
